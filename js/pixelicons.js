/**
 * Reads an authored map and adds the generated outline.
 * @returns {string[][]} GRID rows of GRID tone characters, '.' for empty
 */
export function resolveIcon(key) {
  const src = PIXEL_ICONS[key];
  if (!src) throw new Error('no pixel icon: ' + key);
  const cells = src.map(row => row.padEnd(GRID, '.').slice(0, GRID).split(''));
  // Eight-neighbour, so a diagonal step gets its corner pixel and the outline
  // never breaks. A four-neighbour ring leaves a gap on every 45deg edge.
  const out = cells.map(r => r.slice());
  for (let y = 0; y < GRID; y++) {
    for (let x = 0; x < GRID; x++) {
      if (cells[y][x] !== '.') continue;
      let touches = false;
      for (let dy = -1; dy <= 1 && !touches; dy++) {
        for (let dx = -1; dx <= 1; dx++) {
          const ny = y + dy;
          const nx = x + dx;
          if (ny < 0 || ny >= GRID || nx < 0 || nx >= GRID) continue;
          if (cells[ny][nx] !== '.') { touches = true; break; }
        }
      }
      if (touches) out[y][x] = '0';
    }
  }
  return out;
}

// ---- geometry ------------------------------------------------------------
//
// One merged, non-indexed, vertex-coloured BufferGeometry per icon, so the
// whole thing is a single draw call however many pixels it has. Interior faces
// between neighbouring pixels are never emitted - only the front, the back and
// whatever side walls are actually exposed - which is why a 200-pixel icon
// costs a few hundred triangles rather than 200 boxes.
//
// UNLIT ON PURPOSE. MeshBasicMaterial, no lights, no shading: the moment a
// light rakes across the face it stops being flat art. The shading is painted
// into the tones, and the only thing that gives the object away as solid is
// the darker colour on the side walls.

function quad(pos, col, a, b, c, d, color) {
  for (const v of [a, b, c, a, c, d]) pos.push(v[0], v[1], v[2]);
  for (let i = 0; i < 6; i++) col.push(color.r, color.g, color.b);
}

// Geometry is cached by (icon, colour) and shared. The tones are baked into a
// vertex attribute rather than a uniform - four of the five are derived from
// the theme with different saturations, so they are not one hue times one
// number and cannot be collapsed into a material colour - which means the
// buffer does depend on the colour. Without this cache each of the three
// totems would build its own copy of every offer it ever showed, and the
// geometry count would grow with totems x pool instead of with the pool.
const geoCache = new Map();

function iconGeometry(key, color) {
  const ck = key + '|' + color;
  let g = geoCache.get(ck);
  if (g) return g;
  const cells = resolveIcon(key);
  const pal = pixelPalette(color);
  const pos = [];
  const col = [];
  const half = GRID / 2;
  const zf = DEPTH / 2;
  const zb = -DEPTH / 2;
  const filled = (x, y) => x >= 0 && x < GRID && y >= 0 && y < GRID && cells[y][x] !== '.';

  for (let y = 0; y < GRID; y++) {
    for (let x = 0; x < GRID; x++) {
      const t = cells[y][x];
      if (t === '.') continue;
      const x0 = (x - half) * PX;
      const x1 = x0 + PX;
      // Row 0 is the TOP row, so y runs down the grid and up the world.
      const y1 = (half - y) * PX;
      const y0 = y1 - PX;
      const face = pal[t];
      const side = pal.side;
      // The face. This is the art; everything else is the slab it sits on.
      quad(pos, col, [x0, y0, zf], [x1, y0, zf], [x1, y1, zf], [x0, y1, zf], face);
      // The back, seen only as the icon swings past - kept dark so it never
      // competes with the front.
      quad(pos, col, [x1, y0, zb], [x0, y0, zb], [x0, y1, zb], [x1, y1, zb], side);
      if (!filled(x - 1, y)) quad(pos, col, [x0, y0, zb], [x0, y0, zf], [x0, y1, zf], [x0, y1, zb], side);
      if (!filled(x + 1, y)) quad(pos, col, [x1, y0, zf], [x1, y0, zb], [x1, y1, zb], [x1, y1, zf], side);
      if (!filled(x, y - 1)) quad(pos, col, [x0, y1, zf], [x1, y1, zf], [x1, y1, zb], [x0, y1, zb], side);
      if (!filled(x, y + 1)) quad(pos, col, [x0, y0, zb], [x1, y0, zb], [x1, y0, zf], [x0, y0, zf], side);
    }
  }

  g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
  g.setAttribute('color', new THREE.Float32BufferAttribute(col, 3));
  g.computeBoundingSphere();
  geoCache.set(ck, g);
  return g;
}

/**
 * Builds one pixel icon. The caller owns the returned group and should keep
 * it; the geometry inside is shared, but the material is not - it carries the
 * pulse, so every icon needs its own.
 *
 * @param {string} key    an entry in PIXEL_ICONS
 * @param {number} color  the offer's theme colour
 * @returns {THREE.Group}
 */
/**
 * The same drawing, rendered flat for the DOM.
 *
 * The HUD's buff chips wear the icons the pickups wear - one drawing, two
 * renderers - so a red chip in the corner and the red thing that was picked up
 * off the floor are visibly the same object. Returns a canvas at GRID*scale
 * pixels; the caller sizes it with CSS and sets image-rendering: pixelated.
 *
 * Built once per chip and never per frame: this walks 576 cells.
 */
export function pixelIconCanvas(key, color, scale = 2) {
  const cells = resolveIcon(key);
  const pal = pixelPalette(color);
  const cv = document.createElement('canvas');
  cv.width = GRID * scale;
  cv.height = GRID * scale;
  const g = cv.getContext('2d');
  const css = new Map();
  for (const k of Object.keys(pal)) css.set(k, '#' + pal[k].getHexString());
  for (let y = 0; y < GRID; y++) {
    for (let x = 0; x < GRID; x++) {
      const t = cells[y][x];
      if (t === '.') continue;
      g.fillStyle = css.get(t) || '#fff';
      g.fillRect(x * scale, y * scale, scale, scale);
    }
  }
  return cv;
}

export function buildPixelIcon(key, color) {
  const mat = new THREE.MeshBasicMaterial({ vertexColors: true });
  const group = new THREE.Group();
  group.add(new THREE.Mesh(iconGeometry(key, color), mat));

  // totems.js pulses `icon.userData.glow.emissiveIntensity` every frame. There
  // is no emissive here - the material is unlit - so the same write is taken as
  // a brightness multiplier on the whole plate instead. Standing in for the old
  // interface rather than changing the caller keeps this a drop-in: nothing
  // outside this file has to know which catalogue built the icon.
  group.userData.glow = {
    set emissiveIntensity(v) {
      mat.color.setScalar(Math.min(1.6, 0.55 + v * 0.33));
    },
    get emissiveIntensity() { return 1; },
  };
  return group;
}
